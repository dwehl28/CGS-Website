function compile(relative,overrides={}) {
  const filename=path.resolve(__dirname,'..',relative), loaded=new Module(filename,module);
  loaded.filename=filename;loaded.paths=module.paths;
  loaded.require=(name)=>Object.hasOwn(overrides,name)?overrides[name]:module.require(name);
  loaded._compile(ts.transpileModule(fs.readFileSync(filename,'utf8'),{compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2022}}).outputText,filename);
  return loaded.exports;
}
