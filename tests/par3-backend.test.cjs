function finishPools(h) {
  let id=0;
  h.tables.cgs_par3_pool_matches=h.event.pool_sizes.flatMap((_,index)=>{
    const ids=h.players.filter(p=>p.pool_number===index+1).map(p=>p.id),rows=[];let match=0;
    for(let i=0;i<ids.length;i++)for(let j=i+1;j<ids.length;j++)rows.push({id:++id,event_id:1,pool_number:index+1,match_number:++match,player1_id:ids[i],player2_id:ids[j],winner_id:ids[i],status:'complete',bay_number:null,updated_at:'',created_at:''});
    return rows;
  });
}
