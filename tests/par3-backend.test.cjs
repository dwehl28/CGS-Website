test('fifteen-player finals play through to a champion while the bye remains protected',async()=>{
  const h=harness([4,4,4,4,4],16,[3,3,3,3,3]);h.event.finals_format='pool_winners_ctp_bye';
  for(const p of h.players)p.pool_rank_override=p.rank;h.players[0].ctp_rank=1;
  await h.api.generatePar3Knockout(1);h.event.knockout_data=h.calls[0].args.p_knockout_data;h.calls.length=0;
  const initial=h.event.knockout_data,firstId=initial.round.find(r=>r.number===1).id;
  const originalBye=structuredClone(initial.match.find(m=>m.round_id===firstId&&(m.opponent1===null||m.opponent2===null)));
  let played=0;
  for(;;){
    const ready=h.event.knockout_data.match.find(m=>m.status===2&&m.opponent1?.id!=null&&m.opponent2?.id!=null);
    if(!ready)break;
    await h.api.recordPar3KnockoutWinner(1,ready.id,1);
    const saved=h.calls.at(-1);assert.equal(saved.name,'table_update');h.event.knockout_data=saved.values.knockout_data;played++;
  }
  assert.equal(played,14);
  const lastRound=h.event.knockout_data.round.find(r=>r.number===4).id,final=h.event.knockout_data.match.find(m=>m.round_id===lastRound);
  assert.equal(final.status,4);assert.equal(final.opponent1.result,'win');
  const champion=h.event.knockout_data.participant.find(p=>p.id===final.opponent1.id);assert.ok(champion);
  const finalBye=h.event.knockout_data.match.find(m=>m.id===originalBye.id);
  assert.deepEqual(finalBye.opponent1,originalBye.opponent1);assert.equal(finalBye.opponent2,null);
  assert.ok(finalBye.status===0||finalBye.status===5);
  await assert.rejects(h.api.resetPar3KnockoutMatch(1,originalBye.id),/bye advances automatically/);
});
